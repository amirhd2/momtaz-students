export type DetectedGender = 'MALE' | 'FEMALE' | null;

/**
 * تشخیص جنسیت از نام و نام خانوادگی:
 * - واژه اول به‌عنوان نام کوچک بررسی می‌شود
 * - پیشوند «سیده» → دختر و پیشوند «سید» → بر اساس نام بعدی
 * - اگر نام در دیکشنری نباشد null برمی‌گردد (انتخاب دستی در پیش‌نمایش)
 */
export function detectGender(fullName: string): DetectedGender {
  const norm = normalizeFa(fullName);
  const tokens = norm.split(' ').filter(Boolean);
  if (tokens.length === 0) return null;

  const first = tokens[0];
  if (first === 'سیده') return 'FEMALE';
  if (first === 'سید') {
    const second = tokens[1];
    if (second && FEMALE_NAMES.has(second)) return 'FEMALE';
    return 'MALE';
  }

  if (MALE_NAMES.has(first)) return 'MALE';
  if (FEMALE_NAMES.has(first)) return 'FEMALE';
  return null;
}

/** تفسیر متن ستون جنسیت در فایل اکسل */
export function parseGenderText(text: string): DetectedGender | 'invalid' {
  const norm = normalizeFa(text);
  if (!norm) return null;
  if (/^(دختر|د|ز|زن|خانم|بانو|مؤنث|مونث|female|f|ف)$/.test(norm)) return 'FEMALE';
  if (/^(پسر|پ|م|مرد|اقا|آقا|مذکر|male|m)$/.test(norm)) return 'MALE';
  return 'invalid';
}
