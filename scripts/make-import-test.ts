// ساخت فایل اکسل تستی برای ورود گروهی — سناریوهای مختلف
import ExcelJS from 'exceljs';

const wb = new ExcelJS.Workbook();
const ws = wb.addWorksheet('دانش‌آموزان', { views: [{ rightToLeft: true }] });

ws.addRow([
  'نام و نام خانوادگی دانش‌آموز',
  'مقطع تحصیلی',
  'معدل',
  'نام والد شاغل در سازمان',
  'طبقه',
  'واحد',
  'جنسیت (اختیاری)',
]);

// 1) جنسیت خالی → تشخیص خودکار: علی = پسر | معدل اعشاری عددی
ws.addRow(['علی محمدی', 'پایه هفتم', 19.75, 'حسن محمدی', 2, 'فناوری اطلاعات', '']);
// 2) جنسیت خالی → فاطمه = دختر | مقطع بازه | معدل خالی → خیلی خوب خودکار
ws.addRow(['فاطمه حسینی', 'اول تا سوم', '', 'رضا حسینی', 1, 'مالی', '']);
// 3) معدل کمتر از حد (15 < 18) → استثنا
ws.addRow(['محمد رضایی', 'پایه دهم', 15, 'علی رضایی', 2, 'پشتیبانی', 'پسر']);
// 4) جنسیت از ستون + مقطع عددی فارسی + معدل ممیز فارسی
ws.addRow(['زهرا موسوی', '۹', '۱۹/۵', 'اکبر موسوی', '۳', 'حراست', 'دختر']);
// 5) نام تکراری با رکورد موجود بخش (علی سجودی)
ws.addRow(['علی سجودی', 'چهارم تا ششم', 'خیلی خوب', 'محمود سجودی', 2, 'مالی', '']);
// 6) نام خالی → خطا
ws.addRow(['', 'پایه دوم', '', 'کسی', 1, '—', '']);
// 7) مقطع نامعتبر → خطا
ws.addRow(['کاوه رستمی', 'پایه سیزدهم', 18, 'رستمی', 2, 'IT', '']);
// 8) نام ناشناخته برای تشخیص جنسیت → انتخاب دستی (آرتین در دیکشنری نیست)
ws.addRow(['آرتین نادری', 'دانشگاه', 17.5, 'نادری', 4, 'IT', '']);
// 9) تکراری داخل خود فایل
ws.addRow(['سارا اکبری', 'پایه ششم', '', 'اکبری', 1, 'آموزش', 'دختر']);
ws.addRow(['سارا اکبری', 'پایه ششم', '', 'اکبری', 1, 'آموزش', 'دختر']);
// 10) معدل برای مقطع عددی خالی → خطا
ws.addRow(['حسین قاسمی', 'پایه نهم', '', 'قاسمی', 2, 'بهداشت', 'مرد']);

await wb.xlsx.writeFile('/tmp/import-test.xlsx');
console.log('written /tmp/import-test.xlsx');
